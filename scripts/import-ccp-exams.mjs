// Converts the practice exams from github.com/kananinirav/AWS-Certified-Cloud-Practitioner-Notes
// (MIT licensed) into the app's question format.
// Usage: node scripts/import-ccp-exams.mjs <path-to-cloned-repo>
import fs from 'node:fs';
import path from 'node:path';

const repo = process.argv[2];
if (!repo) throw new Error('Usage: node scripts/import-ccp-exams.mjs <path-to-cloned-repo>');
const srcDir = path.join(repo, 'practice-exam');
const outDir = new URL('../src/data/exams/clf-c02/', import.meta.url).pathname;

const clean = (s) =>
  s
    .replace(/<\/?[^>]+>/g, '') // stray HTML
    .replace(/<(https?:\/\/[^>]+)>/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();

function parse(md, examNo) {
  const questions = [];
  const problems = [];
  let q = null;
  let section = null; // 'question' | 'option' | 'details' | 'explanation'

  const push = () => {
    if (!q) return;
    const n = questions.length + 1;
    const item = {
      id: `pe${examNo}-${String(n).padStart(2, '0')}`,
      question: clean(q.question),
      options: q.options.map((o) => clean(o).replace(/\.$/, '')),
      answer: q.answer,
      explanation: clean(q.explanation),
    };
    if (!item.options.length) problems.push(`Q${n}: no options`);
    if (!item.answer.length) problems.push(`Q${n}: no answer`);
    if (item.answer.some((i) => i >= item.options.length)) problems.push(`Q${n}: answer out of range`);
    questions.push(item);
  };

  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    let m;
    if ((m = line.match(/^\d+\.\s+(.*)/))) {
      push();
      q = { question: m[1], options: [], answer: [], explanation: '' };
      section = 'question';
    } else if (!q) {
      continue;
    } else if ((m = line.match(/^\s*[-*]\s*([A-H])[.)]\s*(.*)/)) && section !== 'details' && section !== 'explanation') {
      q.options.push(m[2]);
      section = 'option';
    } else if (/<details/i.test(line)) {
      section = 'details';
    } else if ((m = line.match(/Correct answer:\s*([A-H ,]+)/i))) {
      q.answer = [...m[1].replace(/[^A-H]/g, '')].map((c) => c.charCodeAt(0) - 65);
    } else if ((m = line.match(/Explanation:\s*(.*)/i))) {
      q.explanation = m[1];
      section = 'explanation';
    } else if (/<\/details>/i.test(line)) {
      section = null;
    } else if (line.trim()) {
      if (section === 'question') q.question += ` ${line.trim()}`;
      else if (section === 'option') q.options[q.options.length - 1] += ` ${line.trim()}`;
      else if (section === 'explanation') q.explanation += ` ${line.trim()}`;
    }
  }
  push();
  return { questions, problems };
}

const files = fs
  .readdirSync(srcDir)
  .map((f) => f.match(/^practice-exam-(\d+)\.md$/))
  .filter(Boolean)
  .map((m) => Number(m[1]))
  .sort((a, b) => a - b);

// Remove previously generated exams so the folder mirrors the source.
for (const f of fs.readdirSync(outDir)) if (/^practice-exam-\d+\.js$/.test(f)) fs.unlinkSync(path.join(outDir, f));

const index = [];
for (const n of files) {
  const md = fs.readFileSync(path.join(srcDir, `practice-exam-${n}.md`), 'utf8');
  const { questions, problems } = parse(md, n);
  fs.writeFileSync(
    path.join(outDir, `practice-exam-${n}.js`),
    `// Generated by scripts/import-ccp-exams.mjs. Do not edit by hand.\nexport default ${JSON.stringify(questions, null, 2)};\n`,
  );
  index.push(n);
  const multi = questions.filter((q) => q.answer.length > 1).length;
  console.log(`Exam ${n}: ${questions.length} questions (${multi} multi-answer)${problems.length ? '  ⚠ ' + problems.join('; ') : ''}`);
}

fs.writeFileSync(
  path.join(outDir, 'index.js'),
  `// Generated by scripts/import-ccp-exams.mjs. Do not edit by hand.\n` +
    index.map((n) => `import pe${n} from './practice-exam-${n}.js';`).join('\n') +
    `\n\nexport default [\n` +
    index.map((n) => `  { id: 'practice-exam-${n}', title: 'Practice Exam ${n}', questions: pe${n} },`).join('\n') +
    `\n];\n`,
);
